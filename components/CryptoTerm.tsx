"use client";

/**
 * CryptoTerm - wraps a cryptographic term with a quiet tooltip that reveals
 * a one-line plain-language definition. Respects hover-capable vs touch,
 * focus, keyboard (Enter toggles, Escape closes), and
 * `prefers-reduced-motion` (via the panel's CSS transition).
 *
 * Not a CSS `title` attribute - that's native tooltip chrome. This renders
 * its own panel so it theme-adapts across Eclipse / Dusk / Grid.
 */

import {
  forwardRef,
  useCallback,
  useEffect,
  useId,
  useRef,
  useState,
  type KeyboardEvent as ReactKeyboardEvent,
  type ReactNode,
} from "react";

/**
 * Plain-language glossary. Every definition is one sentence, cites the
 * primitive honestly, and avoids marketing language.
 */
const GLOSSARY: Record<string, string> = {
  "Kyber-768":
    "NIST post-quantum key-encapsulation mechanism (ML-KEM-768). 1184-byte public keys, hard under quantum attack.",
  "ML-KEM-768":
    "Standardised name for Kyber-768 under NIST FIPS 203. Hard under quantum attack.",
  "ML-DSA-65":
    "NIST post-quantum signature scheme (FIPS 204). Used for attestation authentication between relay and nodes.",
  "RISC0 STARK":
    "A zero-knowledge proof generated by the RISC0 zkVM. STARKs are hash-based, so they stay hard under quantum attack.",
  STARK:
    "Scalable Transparent Argument of Knowledge. Hash-based, quantum-safe, no trusted setup.",
  "ChaCha20-Poly1305":
    "An authenticated stream cipher. Sombra uses it to encrypt UTXO payloads, keyed by a Kyber-derived shared secret.",
  "SHA-256":
    "A cryptographic hash. Used for commitments, PDA seeds, and UTXO addressing.",
  UTXO:
    "Unspent Transaction Output. Sombra values are encrypted notes, spent in whole.",
  "Solana L1":
    "The base Solana blockchain. Proofs and ciphertexts are submitted and verified here.",
  ECDSA:
    "Elliptic-curve signature scheme. Broken by Shor's algorithm on a working quantum computer.",
  ECC:
    "Elliptic-curve cryptography. The basis of ECDSA and most current blockchains. Broken by quantum attack.",
  KEM:
    "Key-encapsulation mechanism. Exchanges a symmetric key under asymmetric cryptography.",
  AEAD:
    "Authenticated encryption with associated data. Encrypts and authenticates in one pass.",
  SNARK:
    "Succinct Non-interactive Argument of Knowledge. Smaller and faster than STARKs, but relies on elliptic-curve cryptography - broken by quantum attack.",
  "Signature-free":
    "Sombra uses zero-knowledge proofs instead of digital signatures. You prove you own the inputs without signing - the proof is the authorization.",
  "No nullifiers":
    "Sombra doesn't use a global nullifier set to mark spent notes. UTXOs chain per-vault via ZK proof of inclusion - no growing public accumulator to leak timing metadata.",
  "attestation quorum":
    "A minimum number of prover nodes must independently verify the ZK proof before a UTXO is finalized. Quorum distributes trust across validators, not a single prover.",
};

type Variant = "inline" | "bare";

export interface CryptoTermProps {
  term: keyof typeof GLOSSARY | string;
  children?: ReactNode;
  variant?: Variant;
  description?: string;
  className?: string;
}

export const CryptoTerm = forwardRef<HTMLSpanElement, CryptoTermProps>(
  function CryptoTerm(
    { term, children, variant = "inline", description, className },
    ref,
  ) {
    const [open, setOpen] = useState(false);
    const [canHover, setCanHover] = useState(false);
    const triggerRef = useRef<HTMLSpanElement | null>(null);
    const setRefs = (el: HTMLSpanElement | null) => {
      triggerRef.current = el;
      if (typeof ref === "function") ref(el);
      else if (ref)
        (ref as React.MutableRefObject<HTMLSpanElement | null>).current = el;
    };
    const tooltipId = useId();

    const body = description ?? GLOSSARY[term] ?? "";

    useEffect(() => {
      if (typeof window === "undefined") return;
      const mq = window.matchMedia("(hover: hover) and (pointer: fine)");
      const update = () => setCanHover(mq.matches);
      update();
      mq.addEventListener("change", update);
      return () => mq.removeEventListener("change", update);
    }, []);

    // Outside-tap dismiss for touch.
    useEffect(() => {
      if (!open || canHover) return;
      const onDocPointer = (e: PointerEvent) => {
        if (!triggerRef.current) return;
        if (triggerRef.current.contains(e.target as Node)) return;
        setOpen(false);
      };
      document.addEventListener("pointerdown", onDocPointer);
      return () => document.removeEventListener("pointerdown", onDocPointer);
    }, [open, canHover]);

    // Escape dismisses while open.
    useEffect(() => {
      if (!open) return;
      const onKey = (e: KeyboardEvent) => {
        if (e.key === "Escape") {
          setOpen(false);
          triggerRef.current?.blur();
        }
      };
      document.addEventListener("keydown", onKey);
      return () => document.removeEventListener("keydown", onKey);
    }, [open]);

    const onKeyDown = useCallback(
      (e: ReactKeyboardEvent<HTMLSpanElement>) => {
        if (e.key === "Enter" || e.key === " ") {
          e.preventDefault();
          setOpen((v) => !v);
        }
      },
      [],
    );

    const hoverHandlers = canHover
      ? {
          onMouseEnter: () => setOpen(true),
          onMouseLeave: () => setOpen(false),
        }
      : {
          onClick: (e: React.MouseEvent) => {
            e.stopPropagation();
            setOpen((v) => !v);
          },
        };

    if (!body) {
      return (
        <span ref={setRefs} className={className}>
          {children ?? term}
        </span>
      );
    }

    return (
      <span
        ref={setRefs}
        tabIndex={variant === "inline" ? 0 : -1}
        aria-describedby={tooltipId}
        onFocus={() => setOpen(true)}
        onBlur={() => setOpen(false)}
        onKeyDown={onKeyDown}
        {...hoverHandlers}
        className={[
          "crypto-term",
          variant === "inline" ? "crypto-term--inline" : "",
          className ?? "",
        ]
          .filter(Boolean)
          .join(" ")}
      >
        <span>{children ?? term}</span>
        <span
          id={tooltipId}
          role="tooltip"
          aria-hidden={!open}
          data-open={open}
          className="crypto-term__panel"
        >
          {body}
        </span>
      </span>
    );
  },
);
